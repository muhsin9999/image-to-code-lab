import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { requireDependency } from '../src/common.mjs';
import { responsiveStarterCss } from '../src/responsive-starter.mjs';
import { fastInit, fastReview, fastCheck, fastRestoreBest } from '../src/fast.mjs';
const { chromium } = requireDependency('playwright');
const out = path.resolve('benchmarks/reviewed-workflow-smoke',new Date().toISOString().replace(/[:.]/g,'-'));
await fs.mkdir(out,{recursive:true});
const screenshot=path.join(out,'target.png'),work=path.join(out,'work'),site=path.join(out,'site');
const css=responsiveStarterCss+'body{font:16px Arial;color:#222;background:#fafafa}.page{padding:24px}h1{font-size:32px}section{display:grid;grid-template-columns:repeat(auto-fit,minmax(min(100%,160px),1fr));gap:16px}article{padding:16px;background:#e4edf4}';
const body='<main class="page"><h1>Browse the collection</h1><p>Independent cards adapt to the screen.</p><section><article><h2>First item</h2><p>Available today</p></article><article><h2>Second item</h2><p>Available tomorrow</p></article></section></main>';
const browser=await chromium.launch({headless:true,...(process.platform==='win32'?{executablePath:process.env.CHROME_PATH||'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe'}:{})});
try {const page=await browser.newPage({viewport:{width:640,height:600}});await page.setContent(`<style>${css}</style>${body}`);await page.screenshot({path:screenshot});}finally{await browser.close();}
const init=await fastInit({screenshot,out:work,site,maxMinutes:.0001});
const facts=JSON.parse(await fs.readFile(path.join(work,'facts.json'),'utf8'));
const plan={version:1,containers:facts.sections.map(s=>({id:s.id,role:'section',items:s.items.map(i=>i.id),layout:'Container in document flow with a wrapping card grid.',responsive:'Cards stack when space is insufficient; paragraphs wrap.'})),corrections:[],assets:[],uncertainties:[]};
const planFile=path.join(out,'plan.json');await fs.writeFile(planFile,JSON.stringify(plan));
await fastReview({out:work,plan:planFile});
// Known HTML is used only in this integration test, never in the isolated agent pack.
await fs.writeFile(path.join(site,'src','App.tsx'),`export function App(){return <div dangerouslySetInnerHTML={{__html:${JSON.stringify(body)}}}/>}`);
await fs.writeFile(path.join(site,'src','style.css'),css);
const originalFit=await fs.readFile(path.join(site,'src','fit.css'),'utf8');
const first=await fastCheck({out:work});
assert.equal(await fs.readFile(path.join(site,'src','style.css'),'utf8'),css);
assert.equal(await fs.readFile(path.join(site,'src','fit.css'),'utf8'),originalFit);
const responsive=JSON.parse(await fs.readFile(path.join(work,'runs','run-01','responsive.json'),'utf8'));
assert.deepEqual(responsive.map(r=>r.width),[640,768,390]);
assert.ok(responsive.every(r=>!r.issues.some(i=>['overflow','offscreen','covered-content','runtime-error'].includes(i.kind))));
await fs.appendFile(path.join(site,'src','style.css'),'\n.page{width:1300px}');
const second=await fastCheck({out:work});
assert.equal(second.best.run,1,'A wider broken layout must not become the best run.');
assert.ok(second.markdown.includes('Page width'));
await fastRestoreBest({out:work});
assert.equal(await fs.readFile(path.join(site,'src','style.css'),'utf8'),css);
const final=await fastCheck({out:work});
assert.equal(final.status,'over-target');
assert.ok(final.markdown.includes('not a quality pass'));
const extra=await fastCheck({out:work});
assert.equal(extra.run,4);assert.equal(extra.extraRound,true);
assert.ok(extra.budget.exhausted);
await fs.writeFile(path.join(out,'summary.json'),JSON.stringify({passed:true,factsSeconds:init.timingsMs.total/1000,rounds:4,firstDiff:first.differingFraction,best:final.best,checks:['review works after deadline','source styles unchanged','three viewports','regression rejected','restore rebuilt','over-target distinct from acceptance','extra rounds stay available']},null,2));
console.log(`Reviewed workflow passed, including regression and restore. Evidence: ${out}`);
